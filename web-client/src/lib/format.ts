// ═══════════════════════════════════════════════════════════════════
//  Человекочитаемые размеры файлов.
//
//  Раньше размер в чате считался так:
//      (bytes / 1024 / 1024).toFixed(1) + ' МБ'
//
//  Для файла в 576 байт это даёт «0.0 МБ», и выглядит как будто размер
//  не показывается вовсе. Так было в четырёх местах ChatArea и ещё в
//  нескольких компонентах — каждое со своей копией той же ошибки.
//
//  Здесь единица подбирается по величине, поэтому мелкие файлы видны
//  как «576 Б», а не как ноль.
// ═══════════════════════════════════════════════════════════════════

const UNITS = ['Б', 'КБ', 'МБ', 'ГБ', 'ТБ'] as const;

/**
 * Размер в байтах → строка с подходящей единицей.
 * Некорректный вход (undefined, NaN, отрицательное) даёт пустую строку,
 * а не «NaN МБ»: лучше не показать ничего, чем показать мусор.
 */
export function formatBytes(bytes: number | null | undefined): string {
  if (bytes === null || bytes === undefined) return '';
  const n = Number(bytes);
  if (!Number.isFinite(n) || n < 0) return '';
  if (n === 0) return '0 Б';

  const i = Math.min(
    Math.floor(Math.log(n) / Math.log(1024)),
    UNITS.length - 1,
  );
  const value = n / Math.pow(1024, i);
  // Байты — всегда целые: «576.0 Б» выглядит нелепо.
  const digits = i === 0 ? 0 : (value < 10 ? 1 : 0);
  return `${parseFloat(value.toFixed(digits))} ${UNITS[i]}`;
}
