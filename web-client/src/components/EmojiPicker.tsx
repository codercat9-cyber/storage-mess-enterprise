// Картинка, не догрузившаяся с первого раза, раньше оставалась пустым
// местом до конца сессии: <img> сам не повторяет. Пробуем ещё дважды с
// паузой; адрес меняем меткой попытки, чтобы не взять из кэша ту же ошибку.
function retryEmojiImage(e: React.SyntheticEvent<HTMLImageElement>) {
  const img = e.currentTarget;
  const tries = Number(img.dataset.tries || '0');
  if (tries >= 2) return;
  img.dataset.tries = String(tries + 1);
  const base = img.src.replace(/&r=\d+$/, '');
  setTimeout(() => { img.src = `${base}&r=${tries + 1}`; }, 1500 * (tries + 1));
}

