// Полная карта: что на самом деле нарисовано на каждой картинке.
//
// Картинок 3593, а имена у них — «группа_номер», и что там изображено, в
// проекте не было записано нигде. Ручная карта ниже покрывала 332 штуки,
// девять процентов. Для остальных поиск вываливал первые двадцать картинок
// подходящей КАТЕГОРИИ — отсюда и «ищешь кота, получаешь любое животное».
//
// Карта построена машинно: наши картинки сопоставлены с эталонным набором
// Apple (он назван кодпоинтами Unicode), а к кодпоинтам подтянуты
// официальные русские названия и слова Unicode CLDR. Покрытие 3592 из 3593.
// Скрипты сопоставления — в journal, раздел про эмодзи.
//
// Лежит на сервере, а не в бандле: 690 КБ исходно, 80 КБ по сети в сжатом
// виде, и нужна только когда человек открыл палитру и начал искать.
// ===========================================================================

interface EmojiMeta { n: string; k: string[]; u?: string }

let keywordsCache: Record<string, EmojiMeta> | null = null;
let keywordsLoading: Promise<Record<string, EmojiMeta>> | null = null;

function loadEmojiKeywords(): Promise<Record<string, EmojiMeta>> {
  if (keywordsCache) return Promise.resolve(keywordsCache);
  if (keywordsLoading) return keywordsLoading;

  keywordsLoading = fetch(`${getBaseUrl()}/emoji/keywords.json?${EMOJI_VER}`)
    .then(r => (r.ok ? r.json() : {}))
    .then((data: Record<string, EmojiMeta>) => {
      keywordsCache = data && typeof data === 'object' ? data : {};
      return keywordsCache;
    })
    .catch(() => {
      // Без карты остаётся ручной список — поиск обеднеет, но не сломается.
      keywordsCache = {};
      return keywordsCache;
    });

  return keywordsLoading;
}

/** Название эмодзи для подписи и подсказки. */
export function getEmojiTitle(catId: number, idx: number): string {
  return keywordsCache?.[`${catId}_${idx}`]?.n || '';
}

