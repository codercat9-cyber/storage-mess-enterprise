function searchEmojis(query: string, _categories: EmojiCategory[]): { catId: number; idx: number }[] {
  if (!query.trim()) return [];
  const q = query.trim().toLowerCase();
  const best = new Map<string, number>();

  const consider = (key: string, word: string) => {
    const w = word.toLowerCase();
    let score = 0;
    if (w === q) score = 100;
    else if (w.startsWith(q)) score = 50;
    // Вхождение в середину («месяц» → «полумесяц») полезно, но слабее.
    else if (w.length >= 3 && w.includes(q)) score = 20;
    // Обратное вхождение («улыбочка» → «улыбка») — только для длинных
    // запросов И длинных слов. Без второго условия предлоги из названий
    // ловят что попало: «и» из «восклицательный и вопросительный знаки»
    // содержится в слове «пицца».
    else if (q.length >= 4 && w.length >= 4 && q.includes(w)) score = 10;
    if (score && score > (best.get(key) || 0)) best.set(key, score);
  };

  // Ручная карта идёт первой и с надбавкой: слова в ней подобраны под то,
  // как люди ищут на самом деле («ржу», «лол»), а не по словарю.
  for (const [key, keywords] of Object.entries(EMOJI_KEYWORDS)) {
    for (const kw of keywords) consider(key, kw);
    const cur = best.get(key);
    if (cur) best.set(key, cur + 5);
  }

  // Полная карта — всё остальное.
  if (keywordsCache) {
    for (const [key, meta] of Object.entries(keywordsCache)) {
      if (meta.n) consider(key, meta.n);
      for (const kw of meta.k) consider(key, kw);
    }
  }

  // Раньше здесь было ещё «если запрос похож на имя категории — показать
  // первые двадцать её картинок». Так поиск по слову «животное» отдавал
  // случайных зверей, а по «кот» — тоже случайных, потому что кота в карте
  // не было. Подстановка убрана: пустой ответ честнее неверного.

  const title = (key: string) => keywordsCache?.[key]?.n || '';
  const seenTitles = new Set<string>();

  return Array.from(best.entries())
    .sort((a, b) => {
      if (b[1] !== a[1]) return b[1] - a[1];
      // При равном счёте вперёд идёт то, чьё название короче: по запросу
      // «огонь» нужен сам огонь, а не женщина-пожарный, у которой это
      // слово тоже в описании.
      return title(a[0]).length - title(b[0]).length;
    })
    // Варианты одного и того же (тон кожи, направление) называются
    // одинаково. В сетке они выглядят как пять копий подряд и вытесняют
    // остальные находки — оставляем первый, остальные человек возьмёт из
    // категории, если нужен конкретный оттенок.
    .filter(([key]) => {
      const t = title(key);
      if (!t) return true;
      if (seenTitles.has(t)) return false;
      seenTitles.add(t);
      return true;
    })
    .slice(0, 60)
    .map(([key]) => {
      const [catStr, idxStr] = key.split('_');
      return { catId: parseInt(catStr), idx: parseInt(idxStr) };
    });
}

export function getEmojiUrl(code: string): string {
  const m = code.match(/^\[e:(\d+_\d+)\]$/);
  if (m) return `${getBaseUrl()}/emoji/${m[1]}.png?${EMOJI_VER}`;
  return '';
}

export function isCustomEmoji(text: string): boolean {
  return /\[e:\d+_\d+\]/.test(text);
}

export function renderTextWithEmoji(content: string): (string | { type: 'emoji'; code: string; src: string })[] {
  const parts: (string | { type: 'emoji'; code: string; src: string })[] = [];
  const regex = /\[e:(\d+_\d+)\]/g;
  let lastIndex = 0;
  let match;
  while ((match = regex.exec(content)) !== null) {
    if (match.index > lastIndex) {
      parts.push(content.slice(lastIndex, match.index));
    }
    parts.push({ type: 'emoji', code: match[0], src: `${getBaseUrl()}/emoji/${match[1]}.png?${EMOJI_VER}` });
    lastIndex = regex.lastIndex;
  }
  if (lastIndex < content.length) {
    parts.push(content.slice(lastIndex));
  }
  return parts;
}

export default function EmojiPicker({ onEmojiSelect, onClose }: EmojiPickerProps) {
  const [activeCategory, setActiveCategory] = useState(0);
  const [categories, setCategories] = useState<EmojiCategory[]>(catalogCache || BUILTIN_CATALOG);
  const [visibleCount, setVisibleCount] = useState(BATCH_SIZE);
  const [searchQuery, setSearchQuery] = useState('');
  const [searchResults, setSearchResults] = useState<{ catId: number; idx: number }[]>([]);
  const pickerRef = useRef<HTMLDivElement>(null);
  const gridRef = useRef<HTMLDivElement>(null);
  const searchInputRef = useRef<HTMLInputElement>(null);

  // Fetch catalog
  useEffect(() => {
    if (catalogCache) {
      setCategories(catalogCache);
      return;
    }
    // Каталог — единственный запрос, без которого панель пустая.
    // Раньше ошибка глушилась пустым catch, и одна неудачная попытка
    // (сеть мигнула, сервер переподнялся) оставляла палитру пустой до
    // закрытия и повторного открытия. Пробуем трижды с нарастающей
    // паузой; отменяем, если компонент уже размонтирован.
    let cancelled = false;
    const controller = new AbortController();

    const load = async (attempt = 0): Promise<void> => {
      try {
        const res = await fetch(`${getApiUrl()}/emoji/catalog`, { signal: controller.signal });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const data = await res.json();
        if (cancelled || !Array.isArray(data?.categories) || data.categories.length === 0) return;
        catalogCache = data.categories;
        setCategories(data.categories);
      } catch (err) {
        if (cancelled || controller.signal.aborted) return;
        if (attempt >= 2) {
          console.warn('Каталог эмодзи не загрузился:', err);
          return;
        }
        await new Promise(r => setTimeout(r, 500 * (attempt + 1)));
        if (!cancelled) return load(attempt + 1);
      }
    };
    void load();

    return () => { cancelled = true; controller.abort(); };
  }, []);

  // Карта названий. Тянем сразу при открытии палитры, но молча и в
  // стороне: без неё сетка рисуется как обычно, просто поиск до её
  // приезда знает только ручные слова.
  const [keywordsReady, setKeywordsReady] = useState(!!keywordsCache);
  useEffect(() => {
    if (keywordsCache) return;
    let cancelled = false;
    void loadEmojiKeywords().then(() => { if (!cancelled) setKeywordsReady(true); });
    return () => { cancelled = true; };
  }, []);

  // Reset visible count on category change
  useEffect(() => {
    setVisibleCount(BATCH_SIZE);
    if (gridRef.current) gridRef.current.scrollTop = 0;
  }, [activeCategory]);

  // Search emojis when query changes.
  // keywordsReady в зависимостях не для красоты: если человек начал
  // печатать раньше, чем приехала карта, результат надо пересчитать —
  // иначе он останется с тем, что нашлось по трёмстам ручным словам.
  useEffect(() => {
    if (searchQuery.trim()) {
      setSearchResults(searchEmojis(searchQuery, categories));
    } else {
      setSearchResults([]);
    }
  }, [searchQuery, categories, keywordsReady]);

  // Infinite scroll - load more as user scrolls down
  const handleScroll = useCallback(() => {
    const el = gridRef.current;
    if (!el) return;
    if (el.scrollTop + el.clientHeight >= el.scrollHeight - 100) {
      setVisibleCount(prev => prev + BATCH_SIZE);
    }
  }, []);

  // Close on click outside
  useEffect(() => {
    const handleClick = (e: MouseEvent) => {
      if (pickerRef.current && !pickerRef.current.contains(e.target as Node)) {
        onClose();
      }
    };
    document.addEventListener('mousedown', handleClick);
    return () => document.removeEventListener('mousedown', handleClick);
  }, [onClose]);

  // Close on Escape
  useEffect(() => {
    const handleKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    document.addEventListener('keydown', handleKey);
    return () => document.removeEventListener('keydown', handleKey);
  }, [onClose]);

  const isSearching = searchQuery.trim().length > 0;
  const currentCategory = categories[activeCategory];
  const currentIndices = currentCategory?.indices.slice(0, visibleCount) || [];

  return (
    <div 
      ref={pickerRef}
      className="emoji-picker w-full bg-messenger-sidebar overflow-hidden"
    >
      {/* Search bar */}
      <div className="px-2 pt-2 pb-1">
        <div className="flex items-center gap-1.5 bg-messenger-hover/60 rounded-lg px-2 py-1">
          <Search size={14} className="text-messenger-muted shrink-0" />
          <input
            ref={searchInputRef}
            type="text"
            value={searchQuery}
            onChange={e => setSearchQuery(e.target.value)}
            placeholder="Поиск эмодзи..."
            className="flex-1 bg-transparent text-[13px] text-messenger-text placeholder-messenger-muted outline-none"
          />
          {searchQuery && (
            <button onClick={() => { setSearchQuery(''); searchInputRef.current?.focus(); }} className="text-messenger-muted hover:text-messenger-text text-xs">✕</button>
          )}
        </div>
      </div>

      {/* Category tabs (hidden during search) */}
      {!isSearching && (
        <div className="flex items-center gap-1 px-2 pt-1 pb-1 border-b border-messenger-border overflow-x-auto no-scrollbar">
        {categories.map((cat, i) => (
          <button
            key={cat.id}
            onClick={() => setActiveCategory(i)}
            className={`flex-shrink-0 w-9 h-9 flex items-center justify-center rounded-lg transition-colors ${
              activeCategory === i 
                ? 'bg-primary-500/20 scale-110' 
                : 'hover:bg-messenger-hover'
            }`}
            title={cat.name}
          >
            <img
              src={`${getBaseUrl()}/emoji/${cat.id}_0.png?${EMOJI_VER}`}
              alt={cat.name}
              className="w-6 h-6"
              loading="lazy"
              onError={retryEmojiImage}
            />
          </button>
        ))}
      </div>
      )}

      {/* Category name / Search results label */}
      <div className="px-3 pt-2 pb-1">
        <span className="text-xs font-medium text-messenger-muted uppercase tracking-wide">
          {isSearching ? (searchResults.length > 0 ? `Найдено: ${searchResults.length}` : 'Ничего не найдено') : currentCategory?.name || ''}
        </span>
      </div>

      {/* Emoji grid */}
      <div ref={gridRef} onScroll={handleScroll} className="h-[220px] overflow-y-auto px-2 pb-2">
        <div className="grid grid-cols-8 gap-0.5">
          {isSearching ? (
            searchResults.map(({ catId, idx }) => (
              <button
                key={`s_${catId}_${idx}`}
                onClick={() => { onEmojiSelect(`[e:${catId}_${idx}]`); setSearchQuery(''); }}
                title={getEmojiTitle(catId, idx)}
                className="w-9 h-9 flex items-center justify-center rounded-lg hover:bg-messenger-hover transition-colors hover:scale-110 p-0.5"
              >
                <img
                  src={`${getBaseUrl()}/emoji/${catId}_${idx}.png?${EMOJI_VER}`}
                  alt={getEmojiTitle(catId, idx)}
                  className="w-full h-full object-contain"
                  loading="lazy"
                  onError={retryEmojiImage}
                  draggable={false}
                />
              </button>
            ))
          ) : (
            currentIndices.map((idx) => (
            <button
              key={`${currentCategory.id}_${idx}`}
              onClick={() => onEmojiSelect(`[e:${currentCategory.id}_${idx}]`)}
              title={getEmojiTitle(currentCategory.id, idx)}
              className="w-9 h-9 flex items-center justify-center rounded-lg hover:bg-messenger-hover transition-colors hover:scale-110 p-0.5"
            >
              <img
                src={`${getBaseUrl()}/emoji/${currentCategory.id}_${idx}.png?${EMOJI_VER}`}
                alt={getEmojiTitle(currentCategory.id, idx)}
                className="w-full h-full object-contain"
                loading="lazy"
                onError={retryEmojiImage}
                draggable={false}
              />
            </button>
          ))
          )}
        </div>
      </div>
    </div>
  );
}
